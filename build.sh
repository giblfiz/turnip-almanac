#!/usr/bin/env bash
# Build a page from src/ and one rules system: the engine (src/app.js) with the rig's UI inserted at /*@RIG-UI@*/.
#   ./build.sh                       → index.html  (Simplified Shadowrun 2e sample: src/scripts.html + rigs/ssr2-ui.js)
#   ./build.sh brp                   → brp.html    (Basic Roleplaying sample: src/scripts-brp.html + rigs/brp-ui.js)
#   ./build.sh <sys>                 → <sys>.html  (src/scripts-<sys>.html + rigs/<sys>-ui.js, plus rigs/<sys>.css if present)
set -euo pipefail
cd "$(dirname "$0")"
# the stencil's fingerprints: one SHA-256 per book file present here, so a table recognises the reader's exact copy
python3 - <<'PY'
import hashlib, json, os
fp = {f: {'sha256': hashlib.sha256(open('books/' + f, 'rb').read()).hexdigest(), 'size': os.path.getsize('books/' + f)} for f in sorted(os.listdir('books')) if f.endswith('.pdf')}
old = open('books/fingerprints.js').read() if os.path.exists('books/fingerprints.js') else ''
try: prev = json.loads(old.split('=', 1)[1].rstrip().rstrip(';')) if old else {}
except Exception: prev = {}
prev.update(fp)   # keep prints of books not on this machine (their PDFs are gitignored elsewhere)
open('books/fingerprints.js', 'w').write('// generated by build.sh: the exact files each stencil was made from\nwindow.BOOK_PRINTS = ' + json.dumps(prev, indent=1) + ';\n')
PY
sys="${1:-ssr2}"
if [ "$sys" = ssr2 ]; then out=index.html; scripts=src/scripts.html; ui=rigs/ssr2-ui.js; else out="$sys.html"; scripts="src/scripts-$sys.html"; ui="rigs/$sys-ui.js"; fi
python3 - "$scripts" "$ui" "$out" <<'PY'
import sys
scripts, ui, out = sys.argv[1:4]
r = lambda p: open(p).read()
app = r('src/app.js'); assert '/*@RIG-UI@*/' in app
app = app.replace('/*@RIG-UI@*/', r(ui), 1)
import os
css = r('src/style.css') + (r(ui.replace('-ui.js', '.css')) if os.path.exists(ui.replace('-ui.js', '.css')) else '')
page = '<!doctype html>\n' + r('src/head.html') + '<style>' + css + '</style>' + r('src/body.html') + r(scripts) + '<script>\n' + app + '</script>\n'
open(out, 'w').write(page); print(f'built {out} ({len(page)} bytes) with {ui}')
PY
