import sys, json
from playwright.sync_api import sync_playwright
out = sys.argv[1]
def q(p, text):
    p.keyboard.press('/'); p.wait_for_timeout(150); p.keyboard.type(text); p.wait_for_timeout(250); p.keyboard.press('Enter'); p.wait_for_timeout(400)
with sync_playwright() as pw:
    b = pw.chromium.launch(args=['--no-sandbox']); p = b.new_page(viewport={'width': 1400, 'height': 900})
    errs = []; p.on('pageerror', lambda e: errs.append('PAGEERR ' + str(e))); p.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
    p.goto('http://127.0.0.1:8471/'); p.wait_for_timeout(2500); p.screenshot(path=f'{out}/01-overview.png')
    def fly(i, name, wait=2600):
        p.evaluate('i => almanac.flyTo(i)', i); p.wait_for_timeout(wait); p.screenshot(path=f'{out}/{name}.png')
    fly('map', '02-map'); fly('pc-tusk', '03-tusk'); fly('builder-pc-tusk', '04-builder')
    fly('s1', '05-sessions-s1'); fly('npc-ruiz', '06-person'); fly('round', '07-round')
    p.click('[data-turn="next"]'); p.wait_for_timeout(200)
    q(p, 'tusk guns'); p.screenshot(path=f'{out}/08-qbar-roll.png'); print('tusk rolls', len(p.evaluate('almanac.state.rolls["pc-tusk"]||[]')))
    q(p, 'roll 6 tn 4'); print('free rolls', len(p.evaluate('almanac.state.rolls._free||[]')))
    q(p, 'damage clutch 2'); print('clutch dmg', p.evaluate('almanac.state.live["pc-clutch"].dmg'))
    p.keyboard.press('/'); p.keyboard.type('ember'); p.wait_for_timeout(300); p.screenshot(path=f'{out}/09-qbar-open.png'); p.keyboard.press('Escape')
    q(p, 'new runner'); p.wait_for_timeout(2600); p.screenshot(path=f'{out}/10-new-name.png')
    nid = p.evaluate('Object.keys(almanac.pcById).find(k=>k.startsWith("pc-x"))'); print('new', nid, p.evaluate('almanac.state.build'))
    p.keyboard.type('Vex'); p.keyboard.press('Tab'); p.wait_for_timeout(2600); print('after tab', p.evaluate('almanac.state.build'))
    p.screenshot(path=f'{out}/11-tab-meta.png')
    p.click(f'[data-pc="{nid}"][data-path="meta"][data-v="elf"]'); p.wait_for_timeout(300)
    p.keyboard.press('Tab'); p.wait_for_timeout(2600); p.keyboard.press('Shift+Tab'); p.wait_for_timeout(2600); print('after shift-tab', p.evaluate('almanac.state.build'))
    p.screenshot(path=f'{out}/12-build-thread.png')
    print('build pills', p.evaluate('[...document.querySelectorAll(".tend.build")].map(e=>e.textContent)'))
    p.evaluate(f'almanac.flyTo("b-{nid}-done")'); p.wait_for_timeout(2600); p.screenshot(path=f'{out}/13-done.png')
    print('done text', p.evaluate(f'document.querySelector("[data-id=b-{nid}-done] .donebox b").textContent'))
    p.click(f'[data-act="finish"][data-pc="{nid}"]'); p.wait_for_timeout(2600); p.screenshot(path=f'{out}/14-finished.png')
    print('finished', p.evaluate('almanac.state.build'), p.evaluate(f'almanac.state.done["{nid}"]'))
    tok = p.evaluate('document.querySelector("[data-id=pc-quill] .tokens button:not(.sel)")?.dataset.tok'); p.evaluate(f'almanac.flyTo("pc-quill")'); p.wait_for_timeout(2600)
    p.click(f'[data-id="pc-quill"] [data-tok="{tok}"]'); p.wait_for_timeout(200); print('portrait now', p.evaluate('document.querySelector("[data-id=pc-quill] .portrait img").getAttribute("src")') == tok)
    p.screenshot(path=f'{out}/15-quill.png')
    p.hover('[data-id="pc-quill"] .main [data-prov="s:magic"]'); p.wait_for_timeout(300); p.screenshot(path=f'{out}/16-threads.png')
    print('ERRS', json.dumps(errs)); b.close()
    f = pw.firefox.launch(); fp = f.new_page(viewport={'width': 1400, 'height': 900}); fp.goto('http://127.0.0.1:8471/'); fp.wait_for_timeout(2500)
    fp.evaluate('almanac.flyTo("map")'); fp.wait_for_timeout(2600)
    c0 = fp.evaluate('[almanac.cam.x, almanac.cam.y]'); fp.mouse.move(700, 450); fp.mouse.down(); fp.mouse.move(500, 350, steps=12); fp.mouse.up(); fp.wait_for_timeout(200)
    c1 = fp.evaluate('[almanac.cam.x, almanac.cam.y]'); print('firefox pan moved', round(c1[0] - c0[0]), round(c1[1] - c0[1])); f.close()
